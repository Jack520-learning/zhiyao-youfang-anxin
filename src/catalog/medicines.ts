export function getMedicine(slug: string): Medicine | undefined {
  return medicines.find((medicine) => medicine.slug === slug);
}

export function getMedicineNames(slugs: string[]): string[] {
  return slugs
    .map((slug) => getMedicine(slug)?.displayName)
    .filter((name): name is string => Boolean(name));
}
